#!/usr/bin/env python3
"""The creator's taste: every correction becomes a rule, so nothing has to be said twice.

Usage:
    python3 tools/taste.py show [--video <slug>]       # rules for the video, counts them as applied
    python3 tools/taste.py add <area> "<rule>" [--video <slug>] [--id N]
    python3 tools/taste.py report                      # what was learned, what had to be said twice
    python3 tools/taste.py forget <id>
    python3 tools/taste.py import --import <legacy.json>   # one-time migration of an old German store

Areas: cut, captions, graphics, sound, delivery, general.
Without --video a rule ALWAYS applies, with --video only to that video.
`add` with --id (or similar wording, same area and scope) updates the old rule instead of
creating a copy. If it was applied since its last change and the user corrects it anyway:
REGRESSION. Then make the rule more concrete (a number, a value), not the same words.

Store: <home>/taste.json (truth) + <home>/TASTE.md (readable, rewritten on every change).
Adapted from NextWork ai-editor (skills/taste), without the settings mapping: the engine reads rules.
"""
import argparse
import datetime
import difflib
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import config  # noqa: E402

HOME = config.home()
STORE = HOME / "taste.json"
MIRROR = HOME / "TASTE.md"
AREAS = ("cut", "captions", "graphics", "sound", "delivery", "general")
SIMILAR = 0.75

# Legacy store (German keys and areas) -> current names.
LEGACY_AREAS = {"schnitt": "cut", "captions": "captions", "grafiken": "graphics", "ton": "sound",
                "abgabe": "delivery", "allgemein": "general"}
LEGACY_FIELDS = {"bereich": "area", "regel": "rule", "seit": "since", "geaendert": "changed",
                 "angewendet": "applied", "seit_aenderung": "applied_since_change",
                 "korrigiert": "corrections", "regressionen": "regressions"}


def today():
    return datetime.date.today().isoformat()


def load():
    if not STORE.exists():
        return []
    with open(STORE, encoding="utf-8") as f:
        return json.load(f)["rules"]


def save(rules):
    HOME.mkdir(parents=True, exist_ok=True)
    with open(STORE, "w", encoding="utf-8") as f:
        json.dump({"rules": rules}, f, ensure_ascii=False, indent=1)
    lines = ["# Taste", "",
             "Generated by `tools/taste.py`, do not edit by hand. Rules beat engine defaults",
             "and the creator.yaml style: the user chose them.", ""]
    for area in AREAS:
        own = [r for r in rules if r["area"] == area]
        if own:
            lines.append(f"## {area}")
            for r in own:
                scope = "always" if not r["video"] else f"only {r['video']}"
                lines.append(f"- #{r['id']} {r['rule']} ({scope}, since {r['since']}, "
                             f"{len(r['applied'])}x applied, {r['regressions']}x regression)")
            lines.append("")
    with open(MIRROR, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def applies(r, video):
    return not r["video"] or r["video"] == video


def find_same(rules, area, rule, video):
    for r in rules:
        if r["area"] == area and r["video"] == video and difflib.SequenceMatcher(
                None, r["rule"].lower(), rule.lower()).ratio() >= SIMILAR:
            return r
    return None


def cmd_add(a, rules):
    if a.area not in AREAS:
        sys.exit(f"✗ unknown area '{a.area}'. One of: {', '.join(AREAS)}")
    old = next((r for r in rules if r["id"] == a.id), None) if a.id else find_same(
        rules, a.area, a.rule, a.video)
    if a.id and not old:
        sys.exit(f"✗ no rule #{a.id} (report lists them all)")
    if old:
        regression = bool(old["applied_since_change"])
        updated = {**old, "area": a.area, "rule": a.rule, "corrections": old["corrections"] + 1,
                   "regressions": old["regressions"] + regression, "changed": today(),
                   "applied_since_change": []}
        rules = [updated if r["id"] == old["id"] else r for r in rules]
        save(rules)
        if regression:
            print(f"REGRESSION #{old['id']}: was applied in {', '.join(old['applied_since_change'])} and did "
                  f"not hold. Make the rule more concrete (a number, a value), not the same words.")
        print(f"Updated #{old['id']}: \"{a.rule}\" ({a.area}, {'always' if not a.video else a.video})")
        return
    new = {"id": max((r["id"] for r in rules), default=0) + 1, "area": a.area, "rule": a.rule,
           "video": a.video, "since": a.since or today(), "changed": a.since or today(), "applied": [],
           "applied_since_change": [], "corrections": 0, "regressions": 0}
    save(rules + [new])
    print(f"Saved #{new['id']}: \"{a.rule}\" ({a.area}, {'always' if not a.video else 'only ' + a.video})")


def cmd_show(a, rules):
    hits = [r for r in rules if applies(r, a.video)]
    if not hits:
        print("No rules yet.")
        return
    if a.video:
        rules = [{**r, "applied": sorted(set(r["applied"]) | {a.video}),
                  "applied_since_change": sorted(set(r["applied_since_change"]) | {a.video})}
                 if applies(r, a.video) else r
                 for r in rules]
        save(rules)
    for area in AREAS:
        for r in (r for r in hits if r["area"] == area):
            print(f"#{r['id']:<3} {area:9} {r['rule']}" + ("" if not r["video"] else f"  [only {r['video']}]"))


def cmd_report(a, rules):
    if not rules:
        print("No rules yet.")
        return
    print(f"{'id':>3}  {'area':9} {'appl.':>6} {'corr.':>5} {'regr.':>5}  rule")
    for r in rules:
        print(f"{r['id']:>3}  {r['area']:9} {len(r['applied']):>6} {r['corrections']:>5} "
              f"{r['regressions']:>5}  {r['rule']}" + ("" if not r["video"] else f"  [only {r['video']}]"))


def cmd_forget(a, rules):
    if not any(r["id"] == a.id for r in rules):
        sys.exit(f"✗ no rule #{a.id}")
    save([r for r in rules if r["id"] != a.id])
    print(f"Forgotten: #{a.id}")


def migrate_rule(old):
    """One legacy rule -> current shape. Rule text verbatim, unknown fields kept as they are."""
    area = LEGACY_AREAS.get(old.get("bereich"))
    if area is None:
        sys.exit(f"✗ legacy rule #{old.get('id')}: unknown area '{old.get('bereich')}'. "
                 f"Known: {', '.join(LEGACY_AREAS)}")
    new = {LEGACY_FIELDS.get(k, k): v for k, v in old.items()}
    since = new.get("since") or today()
    defaults = {"id": new.get("id"), "area": area, "rule": new.get("rule"), "video": None, "since": since,
                "changed": since, "applied": [], "applied_since_change": [], "corrections": 0,
                "regressions": 0}
    return {**defaults, **new, "area": area}


def cmd_import(a, rules):
    path = a.legacy or a.legacy_flag
    if not path:
        sys.exit("✗ no legacy file given: taste.py import --import <legacy.json>")
    if STORE.exists():
        sys.exit(f"✗ {STORE} already exists. Import only runs into an empty store: move it away first.")
    try:
        with open(path, encoding="utf-8") as f:
            legacy = json.load(f)
    except (OSError, json.JSONDecodeError) as e:
        sys.exit(f"✗ legacy file not readable: {e}")
    if not isinstance(legacy, dict) or not isinstance(legacy.get("regeln"), list):
        sys.exit("✗ not a legacy taste file: expected {\"regeln\": [...]}")
    migrated = [migrate_rule(r) for r in legacy["regeln"]]
    save(migrated)
    print(f"Imported {len(migrated)} rules from {path} -> {STORE}")


def main():
    config.use_venv()
    ap = argparse.ArgumentParser(description="The creator's taste: corrections as rules")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("add")
    p.add_argument("area")
    p.add_argument("rule")
    p.add_argument("--video", default=None)
    p.add_argument("--id", type=int, default=None)
    p.add_argument("--since", default=None, help=argparse.SUPPRESS)
    p = sub.add_parser("show")
    p.add_argument("--video", default=None)
    sub.add_parser("report")
    p = sub.add_parser("forget")
    p.add_argument("id", type=int)
    p = sub.add_parser("import", help="migrate a legacy German store into an empty taste.json")
    p.add_argument("legacy", nargs="?", default=None, help="legacy JSON file ({\"regeln\": [...]})")
    p.add_argument("--import", dest="legacy_flag", default=None, metavar="PATH",
                   help="legacy JSON file (same as the positional argument)")
    a = ap.parse_args()
    {"add": cmd_add, "show": cmd_show, "report": cmd_report, "forget": cmd_forget,
     "import": cmd_import}[a.cmd](a, load())


if __name__ == "__main__":
    main()
